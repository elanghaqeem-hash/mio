import assert from 'node:assert/strict';
import { MioNativeInferenceMetrics } from '../../electron/ipc/nativeInferenceMetrics';
import { NativeDesktopChatService } from '../../electron/ipc/nativeLocalChat';
const messages=[{role:'user' as const,content:'Private user content must never appear in telemetry'}];
const ready=()=>Response.json({models:[{name:'qwen2.5:3b'}]});
const answer=()=>Response.json({done:true,model:'qwen2.5:3b',message:{content:'Private model answer'}});
async function main(){
 const metrics=new MioNativeInferenceMetrics();
 assert.equal(metrics.snapshot(0,false).averageDurationMs,null);
 for(let i=1;i<=40;i++)metrics.record('SUCCESS',i);
 const bounded=metrics.snapshot(0,false);
 assert.equal(bounded.accepted,40);
 assert.equal(bounded.succeeded,40);
 assert.equal(bounded.recentSampleCount,32);
 assert.equal(bounded.averageDurationMs,21);
 assert.equal(bounded.p95RecentDurationMs,39);
 assert.equal(bounded.lastDurationMs,40);
 metrics.record('FAILED',Number.POSITIVE_INFINITY);
 assert.equal(metrics.snapshot(1,true).lastDurationMs,300000);
 const service=new NativeDesktopChatService(async url=>String(url).endsWith('/api/tags')?ready():answer(),200);
 const success=await service.chat({messages});
 assert.equal(success.success,true);
 const successInfo=service.inspect();
 assert.equal(successInfo.succeeded,1);
 assert.equal(successInfo.accepted,1);
 assert.equal(successInfo.active,0);
 assert.equal(successInfo.stoppedLatch,false);
 assert.equal(successInfo.localOnly,true);
 assert.equal(successInfo.lastOutcome,'SUCCESS');
 assert.equal(successInfo.recentSampleCount,1);
 assert.ok(Number.isSafeInteger(successInfo.p95RecentDurationMs));
 assert.equal((await service.chat({messages:[]})).success,false);
 assert.equal(service.inspect().accepted,1,'rejected IPC request must not count as inference');
 const flat=JSON.stringify(service.inspect());
 assert.ok(!flat.includes('Private')&&!flat.includes('qwen')&&!flat.includes('127.0.0.1'));
 service.stop();
 assert.equal(service.inspect().stoppedLatch,true);
 assert.equal((await service.chat({messages})).success,false);
 assert.equal(service.inspect().accepted,1);
 const timeout=new NativeDesktopChatService(async()=>new Promise<Response>(()=>{}),15);
 const timed=await timeout.chat({messages});
 assert.equal(timed.error,'MIO_DESKTOP_NATIVE_ABORTED');
 assert.equal(timeout.inspect().timedOut,1);
 assert.equal(timeout.inspect().accepted,1);
 timeout.stop();
 let started:(()=>void)|undefined;
 const readyToBlock=new Promise<void>(resolve=>{started=resolve;});
 const stop=new NativeDesktopChatService(async()=>{
  started?.();
  return new Promise<Response>(()=>{});
 },500);
 const pending=stop.chat({messages});
 await readyToBlock;
 assert.equal(stop.inspect().active,1);
 stop.stop();
 assert.equal((await pending).error,'MIO_DESKTOP_NATIVE_ABORTED');
 assert.equal(stop.inspect().stopped,true);
 assert.equal(stop.inspect().cancelledByStop,1);
 assert.equal(stop.inspect().timedOut,0);
 const failed=new NativeDesktopChatService(async()=>{throw Error('ECONNREFUSED');});
 assert.equal((await failed.chat({messages})).success,false);
 assert.equal(failed.inspect().failed,1);
 failed.stop();
 console.log(JSON.stringify({stage:'M-2.02d',metrics:'pass',privacy:'pass',mockTransport:true,liveOllama:false}));
}
main().catch(e=>{console.error(e);process.exitCode=1;});
